// Regenerates src/codex/glyphs.ts from the game-icons.net set (CC BY 3.0).
// Only the icons listed here ship in the bundle. Run: node scripts/gen-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'));

const WANT = {
  // class crests
  prophet: 'scroll-unfurled', warrior: 'sling', priest: 'candle-light',
  shepherd: 'shepherds-crook', patriarch: 'night-sky', disciple: 'flame', neutral: 'triquetra',
  // menu + screens
  story: 'open-book', freeplay: 'crossed-swords', decks: 'card-pick', packs: 'grain-bundle',
  settings: 'camping-tent', path: 'stone-path', forge: 'anvil',
  // economy + utility
  talents: 'two-coins', fragments: 'crystal-shine', seal: 'wax-seal', lock: 'padlock',
  check: 'check-mark', search: 'magnifying-glass', point: 'pointing', quill: 'quill-ink', bread: 'bread', sheep: 'sheep',
};

const out = Object.entries(WANT).map(([k, name]) => {
  const ic = set.icons[name];
  if (!ic) throw new Error(`missing icon ${name}`);
  return `  ${k}: ${JSON.stringify(ic.body)},  // ${name}`;
});
writeFileSync(new URL('../src/codex/glyphs.ts', import.meta.url),
`/* GENERATED by scripts/gen-glyphs.mjs — do not edit by hand.
 * Icons from game-icons.net by Lorc, Delapouite & contributors, CC BY 3.0
 * (credited in CREDITS.md and the Settings screen). viewBox 0 0 512 512. */
export const GLYPHS = {
${out.join('\n')}
} as const;
export type GlyphName = keyof typeof GLYPHS;
`);
console.log(`wrote ${out.length} glyphs`);
